package com.yellastrodev.dwij.playback

import kotlinx.coroutines.flow.StateFlow

/**
 * Опциональное управление громкостью самого плеера.
 *
 * Значение громкости всегда находится в диапазоне 0f..1f:
 * 0f — полностью без звука,
 * 1f — максимальная громкость приложения.
 *
 * Контракт не является частью PlayerEngine специально:
 * на Android отдельный регулятор громкости приложения не нужен,
 * а desktop backend предоставляет эту возможность отдельно.
 */
interface PlayerVolumeControl {

    /**
     * Текущая громкость приложения в диапазоне 0f..1f.
     */
    val volume: StateFlow<Float>

    /**
     * Устанавливает громкость приложения.
     *
     * Реализация сама ограничивает значение диапазоном 0f..1f.
     */
    fun setVolume(
        volume: Float,
    )

    /**
     * Переключает mute.
     *
     * При повторном включении звука реализация восстанавливает
     * последнюю ненулевую громкость.
     */
    fun toggleMute()
}